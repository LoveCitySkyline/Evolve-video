class ConditioningPlanner:
    def __init__(self, proposer):
        if hasattr(proposer, "codex"):
            raise ValueError("conditioning protocol requires an API planner; Codex filesystem access breaks test isolation")
        self.proposer = proposer
        self.last_usage = None

    def propose(self, request):
        self.last_usage = None
        config = self.proposer.config
        system = (ACTIVE_SYSTEM if request.get("experiment") == "active_factorial" else
                  INTERACTION_SYSTEM if request.get("experiment") == "factorial" else SYSTEM)
        if request.get("condition_only"):
            system += "\nKeep all prompts unchanged. New nodes inherit task/shot prompts. Only change conditioning dependencies, selection, roles and temporal scope."
        payload = {"model": config.model, "messages": [
            {"role": "system", "content": system},
            {"role": "user", "content": json.dumps(request, ensure_ascii=False)}],
            "max_completion_tokens": config.max_output_tokens}
        if config.reasoning_effort:
            payload["reasoning_effort"] = config.reasoning_effort
        response = self.proposer._post(payload)
        self.last_usage = response.get("usage")
        return self.proposer._parse_json(self.proposer._response_content(response))


class ConditioningSmokePlanner:
    """Only checks offline plumbing. It does not simulate empirical improvement."""
    def propose(self, request):
        if request.get("experiment") == "active_factorial":
            raw = self.propose({**request, "experiment": "factorial"})
            return {"anchor": raw["anchor"], "factors": [
                {"id": label, **raw[label]} for label in ("a", "b")]}
        if request.get("experiment") == "factorial":
            anchor = deepcopy(request["parent"])
            a, b = deepcopy(anchor), deepcopy(anchor)
            a["nodes"][-1]["config"]["duration_seconds"] = request["task"]["duration_seconds"]
            b["nodes"][-1]["config"]["reference_ids"] = ["offline_fixture_reference"]
            def strategy(name):
                return {"name": name, "instruction": "Bind conditioning to the requested shot scope.",
                    "hypothesis": "Scope binding may affect constraint satisfaction.",
                    "risks": ["Offline plumbing fixture; no real quality evidence."], "required_references": {}}
            return {"anchor": anchor, "a": {"graph": a, "strategy": strategy("duration_binding")},
                    "b": {"graph": b, "strategy": strategy("shot_binding")},
                    "joint_strategy": strategy("joint_scope_binding")}
        graph = deepcopy(request["parent"])
        if request.get("condition_only"):
            graph["nodes"][-1]["config"]["duration_seconds"] = request["task"]["duration_seconds"]
            memory = request["memory"]
            return {"graph": graph, "strategy": {
                "name": "duration_binding", "instruction": "Bind conditioning to the requested shot scope.",
                "hypothesis": "Scope binding may affect constraint satisfaction.",
                "risks": ["Offline plumbing fixture; no real quality evidence."], "required_references": {}},
                "used_strategy_ids": [request["required_strategy_id"]] if request.get("required_strategy_id") else
                                     [memory[0]["strategy_id"]] if memory else []}
        for node in graph["nodes"]:
            if node["name"] == "mock_text_to_video":
                node["config"]["prompt"] = "Preserve the requested identity and complete each action."
        memory = request["memory"]
        return {"graph": graph, "strategy": {"name": "explicit_identity_constraint",
            "instruction": "Make identity constraints explicit in each generation stage.",
            "hypothesis": "Explicit constraints may improve identity retention.",
            "risks": ["This does not supply missing visual evidence."], "required_references": {}},
            "used_strategy_ids": [memory[0]["strategy_id"]] if memory else []}


def decode_proposal(raw, task, parent, executor, config, memory, required_id=None):
    if not isinstance(raw, dict) or set(raw) != {"graph", "strategy", "used_strategy_ids"}:
        raise ValueError("proposal must contain exactly graph, strategy, used_strategy_ids")
    strategy = validate_strategy(raw["strategy"], task)
    used = raw["used_strategy_ids"]
    known = {x["strategy_id"] for x in memory}
    if not isinstance(used, list) or any(not isinstance(x, str) or x not in known for x in used):
        raise ValueError("proposal cites unknown strategy evidence")
    if required_id is not None and required_id not in used:
        raise ValueError("validation proposal did not instantiate the required strategy")
    graph = decode_graph(raw["graph"])
    if config.get("search_mode", "legacy") != "legacy":
        from evovideo_skill.conditioning_interactions import condition_only
        condition_only(parent, graph)
    validate_candidate(graph, parent, executor, "graph", config["max_nodes"], config["max_edits"])
    return graph, strategy
